import re

def mask(text):
    # 1. +66 93 245 7894  ->  +66 XX XXX 7894
    text = re.sub(r"(?<!\d)\+66([ -]?)[689]\d([ -]?)\d{3}([ -]?)(\d{4})(?!\d)",
                  r"+66\1XX\2XXX\3\4", text)

    # 2. 093-245-7894  ->  XXX-XXX-7894   (ชั้น 1 ตามโจทย์)
    #    \1 = 4 ตัวท้าย
    text = re.sub(r"(?<![\d-])\d{3}-\d{3}-(\d{4})(?![\d-])",
                  r"XXX-XXX-\1", text)

    # 3. 093 245 7894  ->  XXX XXX 7894   ต้องขึ้นต้น 06 08 09
    text = re.sub(r"(?<![\d+])0[689]\d \d{3} (\d{4})(?!\d)",
                  r"XXX XXX \1", text)

    # 4. 0932457894  ->  XXXXXX7894   10 หลักติดกัน ต้องขึ้นต้น 06 08 09
    #    เลขบัญชีขึ้นต้น 1 และเบอร์บ้าน 02 จึงไม่โดน
    text = re.sub(r"(?<![\d+])0[689]\d{4}(\d{4})(?!\d)",
                  r"XXXXXX\1", text)

    return text