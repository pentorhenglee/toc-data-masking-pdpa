import re

# รูปแบบของเลขบัตรเครดิต:
# 1. ชั้น 1 (Tier 1): 16 หลักแบ่ง 4 กลุ่ม คั่นด้วยขีด (1234-5678-9012-3456 -> XXXX-XXXX-XXXX-3456)
# 2. ชั้น 2 (Tier 2):
#    - 16 หลักติดกันไม่มีขีด (1234567890123456 -> XXXXXXXXXXXX3456)
#    - 16 หลักแบ่ง 4 กลุ่ม คั่นด้วยเว้นวรรค (1234 5678 9012 3456 -> XXXX XXXX XXXX 3456)
#    - กันจับผิด: ไม่โดนเลข 12 หลัก (1234-5678-9012), เบอร์โทร (093-245-7894), หรือปีงบประมาณ (Order 2024-2025)
#
# คำอธิบาย Regular Expression:
# (?<![\d-])                 : Negative lookbehind - ข้างหน้าต้องไม่ใช่ตัวเลขหรือขีด ป้องกันการจับส่วนของเลขที่ยาวกว่า
# (?:
#   \d{4}([- ])\d{4}\1\d{4}\1: ตัวเลข 4 หลัก 3 กลุ่มแรก คั่นด้วย '-' หรือ ' ' (โดย \1 บังคับให้ใช้ตัวคั่นเดิมตลอด)
#   |
#   \d{12}                   : หรือ ตัวเลข 12 หลักติดกัน (กรณีไม่มีตัวคั่น)
# )
# (\d{4})                    : กลุ่ม 4 หลักสุดท้าย (Group 2) ที่เก็บไว้ไม่เซ็นเซอร์
# (?![\d-])                  : Negative lookahead - ข้างหลังต้องไม่ใช่ตัวเลขหรือขีด ป้องกันการจับส่วนของเลขที่ยาวกว่า

_CC_PATTERN = re.compile(
    r'(?<![\d-])(?:\d{4}([- ])\d{4}\1\d{4}\1|\d{12})(\d{4})(?![\d-])'
)


def mask(text: str) -> str:
    """
    เซ็นเซอร์เลขบัตรเครดิต โดยคง 4 หลักสุดท้ายไว้
    และรักษาตำแหน่งตัวคั่นเดิม (ขีด หรือ เว้นวรรค) ตามกฎ PDPA
    """
    if not text:
        return text

    def _replace(match: re.Match) -> str:
        sep = match.group(1)
        last4 = match.group(2)
        if sep:
            return f"XXXX{sep}XXXX{sep}XXXX{sep}{last4}"
        return f"XXXXXXXXXXXX{last4}"

    return _CC_PATTERN.sub(_replace, text)
